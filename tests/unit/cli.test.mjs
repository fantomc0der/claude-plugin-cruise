import { test } from 'node:test'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'

import { PLAN, bin, project } from './helpers.mjs'

test('help and usage errors', () => {
  const p = project()
  assert.equal(p.run().status, 2)
  assert.equal(p.run('help').status, 0)
  assert.match(p.run('help').stdout, /cruise start/)
  const r = p.run('bogus')
  assert.equal(r.status, 2)
  assert.equal(r.error.code, 'usage')
})

test('start creates the run, binds the session, and excludes the state dir from git', () => {
  const p = project({ git: true })
  const r = p.run('start', '--session', 's1', 'Add a --json flag')
  assert.equal(r.status, 0, r.stderr)
  assert.match(r.stdout, /^cruise [0-9a-f]{6} · active · phase plan · tasks 0\/0 done · verify 0\/5 · review 0\/2$/m)
  assert.match(r.stdout, /next: write the plan/)
  const s = p.state()
  assert.equal(s.session_id, 's1')
  assert.equal(s.task, 'Add a --json flag')
  assert.equal(s.rev, 1)
  assert.match(p.read('.git/info/exclude'), /^\.cruise\/$/m)
  assert.equal(p.run('status').error, undefined)
  assert.equal(p.run('status', '--json').json.summary, p.run('status').stdout.split('\n')[0])
})

test('start refuses to replace an open run unless forced, and archives the old one', () => {
  const p = project()
  p.run('start', 'first')
  const first = p.state().id
  const again = p.run('start', 'second')
  assert.equal(again.status, 1)
  assert.equal(again.error.code, 'run-exists')
  assert.match(again.error.hint, /--force/)
  assert.equal(p.run('start', '--force', 'second').status, 0)
  assert.notEqual(p.state().id, first)
  assert.ok(existsSync(join(p.dir, '.cruise', 'history')))
  p.run('stop')
  assert.equal(p.run('start', 'third').status, 0)
})

test('limits come from the environment at start', () => {
  const p = project({ env: { CRUISE_MAX_VERIFY_CYCLES: '2', CRUISE_MAX_REVIEW_ROUNDS: '1', CRUISE_MAX_IDLE_NUDGES: '9' } })
  p.run('start', 'x')
  const s = p.state()
  assert.equal(s.verify.max, 2)
  assert.equal(s.review.max, 1)
  assert.equal(s.nudge.max, 9)
  const q = project({ env: { CRUISE_MAX_VERIFY_CYCLES: 'lots' } })
  q.run('start', 'x')
  assert.equal(q.state().verify.max, 5)
})

test('plan import loads the tasks, keeps statuses on re-import, and task commands tick the plan', () => {
  const p = project()
  p.run('start', 'x')
  assert.equal(p.run('plan', 'import').error.code, 'no-plan')
  p.plan(PLAN)
  const imported = p.run('plan', 'import')
  assert.equal(imported.status, 0, imported.stderr)
  assert.match(imported.stdout, /imported 3 task\(s\)/)
  assert.deepEqual(p.state().tasks.map(t => t.status), ['todo', 'todo', 'todo'])
  assert.equal(p.run('task', 'done', '1', 'T2').status, 0)
  assert.deepEqual(p.state().tasks.map(t => t.status), ['done', 'done', 'todo'])
  assert.match(p.read('.cruise/plan.md'), /- \[x\] T1: Parse the flag\n  - files: src\/cli.mjs\n- \[x\] T2: Emit JSON\n- \[ \] T3: Test it/)
  p.run('plan', 'import')
  assert.deepEqual(p.state().tasks.map(t => t.status), ['done', 'done', 'todo'])
  assert.equal(p.run('task', 'block', '3').status, 2)
  p.run('task', 'block', '3', '--reason', 'no runner')
  assert.equal(p.state().tasks[2].note, 'no runner')
  assert.match(p.run('task', 'list').stdout, /T3 blocked Test it \(no runner\)/)
  assert.equal(p.run('task', 'done', '7').error.code, 'no-task')
  assert.equal(p.run('task', 'done', 'seven').status, 2)
  const added = p.run('task', 'add', 'Write docs')
  assert.match(added.stdout, /added T4: Write docs/)
  assert.match(p.read('.cruise/plan.md'), /- \[ \] T3: Test it\n- \[ \] T4: Write docs\n/)
})

test('phases are guarded unless forced', () => {
  const p = project()
  p.run('start', 'x')
  assert.equal(p.run('phase', 'nope').status, 2)
  assert.equal(p.run('phase', 'verify').error.code, 'no-tasks')
  p.plan(PLAN)
  p.run('plan', 'import')
  assert.equal(p.run('phase', 'build').status, 0)
  assert.equal(p.run('phase', 'verify').error.code, 'tasks-open')
  assert.equal(p.run('phase', 'review').error.code, 'verify-not-passed')
  assert.equal(p.run('phase', 'done').error.code, 'not-finished')
  p.run('task', 'done', '1', '2')
  p.run('task', 'block', '3', '--reason', 'later')
  assert.match(p.run('status').stdout, /T3 blocked: unblock and finish/)
  assert.equal(p.run('phase', 'verify').status, 0)
  assert.equal(p.run('phase', 'review', '--force').status, 0)
  const done = p.run('phase', 'done')
  assert.equal(done.error.code, 'not-finished')
  assert.match(done.error.message, /all tasks done or skipped, verify pass, review pass/)
  const forced = p.run('phase', 'done', '--force', '--reason', 'demo')
  assert.equal(forced.status, 0)
  assert.match(forced.stdout, /Report to the user/)
  assert.equal(p.state().status, 'done')
  assert.match(p.run('log').stdout, /force \{"phase":"done","reason":"demo"\}/)
})

test('verify counts cycles, spots a repeating error, and pauses at the limit', () => {
  const p = project({ env: { CRUISE_MAX_VERIFY_CYCLES: '3' } })
  p.run('start', 'x')
  p.plan(PLAN)
  p.run('plan', 'import')
  p.run('task', 'done', '1', '2', '3')
  p.run('phase', 'verify')
  assert.equal(p.run('verify', 'maybe').status, 2)
  let r = p.run('verify', 'fail', 'Error: a broke at src/a.js:1')
  assert.match(r.stdout, /verify cycle 1\/3$/m)
  r = p.run('verify', 'fail', 'Error: b broke at src/b.js:2')
  assert.match(r.stdout, /verify cycle 2\/3$/m)
  r = p.run('verify', 'fail', 'Error: c broke')
  assert.match(r.stdout, /LIMIT: 3 verify cycles used/)
  assert.equal(p.state().status, 'paused')
  assert.match(p.state().pause_reason, /^verify limit/)
  assert.equal(p.run('resume').status, 0)
  assert.equal(p.state().verify.cycles, 0)
  p.run('verify', 'fail', 'Error: same at x.js:1')
  r = p.run('verify', 'fail', 'Error: same at x.js:7')
  assert.match(r.stdout, /same error 2×/)
  r = p.run('verify', 'fail', 'Error: same at x.js:9')
  assert.match(r.stdout, /LIMIT: the same error failed 3 times/)
  assert.equal(p.state().status, 'paused')
  p.run('resume')
  r = p.run('verify', 'pass')
  assert.match(r.stdout, /verify passed: run `cruise phase review`/)
  assert.equal(p.run('phase', 'review').status, 0)
})

test('review rounds pause at the limit, pass unlocks done, and the plan ticks follow', () => {
  const p = project()
  p.run('start', 'x')
  p.plan(PLAN)
  p.run('plan', 'import')
  p.run('task', 'done', '1', '2', '3')
  p.run('phase', 'verify')
  p.run('verify', 'pass')
  p.run('phase', 'review')
  let r = p.run('review', 'fail', '2 blocking')
  assert.match(r.stdout, /review round 1\/2$/m)
  r = p.run('review', 'fail', '1 blocking')
  assert.match(r.stdout, /LIMIT: 2 review rounds used/)
  assert.equal(p.state().status, 'paused')
  p.run('resume')
  r = p.run('review', 'pass')
  assert.match(r.stdout, /review passed: run `cruise phase done`/)
  assert.equal(p.run('phase', 'done').status, 0)
  assert.equal(p.state().status, 'done')
  assert.equal(p.run('resume').error.code, 'run-closed')
})

test('pause, resume, and stop', () => {
  const p = project()
  p.run('start', 'x')
  const paused = p.run('pause', 'Postgres or SQLite?')
  assert.match(paused.stdout, /^paused: Postgres or SQLite\?/)
  assert.equal(p.state().status, 'paused')
  assert.match(p.run('status').stdout, /paused: Postgres or SQLite\?/)
  const resumed = p.run('resume', '--session', 's2')
  assert.equal(resumed.status, 0)
  assert.equal(p.state().status, 'active')
  assert.equal(p.state().session_id, 's2')
  p.run('pause', 'again?')
  p.run('resume')
  assert.equal(p.state().session_id, null)
  const stopped = p.run('stop', '--reason', 'user asked')
  assert.match(stopped.stdout, /· stopped ·/)
  assert.equal(p.state().stop_reason, 'user asked')
  assert.equal(p.run('status', '--json').json.next, 'stopped. Start another run with `cruise start "<task>"`.')
})

test('commands find the run from a subdirectory, and start lands at the git top level', () => {
  const p = project({ git: true })
  const deep = join(p.dir, 'src', 'deep')
  mkdirSync(deep, { recursive: true })
  const inDeep = (...args) => spawnSync(process.execPath, [bin, ...args], { encoding: 'utf8', cwd: deep })
  assert.equal(inDeep('start', 'x').status, 0)
  assert.ok(existsSync(join(p.dir, '.cruise', 'run.json')))
  assert.ok(!existsSync(join(deep, '.cruise')))
  assert.match(inDeep('status').stdout, /· active · phase plan/)
})

